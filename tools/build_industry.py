def top_wards(slug, n=5):
    label = CENSUS_MAP.get(slug)
    if not label:
        return []
    rows = []
    for name, data in CENSUS.items():
        if name not in WARD_SLUG or label not in data:
            continue
        rows.append((name, data[label]["est"]))
    return sorted(rows, key=lambda x: -x[1])[:n]


